/** `containerPort` → "container Port" gibi kaba ama okunur bir dönüşüm. */
export function humanizeKey(key: string): string {
  if (!key) return key;
  const spaced = key.replace(/([a-z0-9])([A-Z])/g, "$1 $2");
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

/**
 * Bir path için etiket üretir. Önce tam path'e bakar (indekssiz — `SchemaField`
 * sayısal segmentleri zaten atmış olmalı), yoksa son segmentin kendisine, o da
 * yoksa `humanizeKey` fallback'ine düşer.
 */
export function labelFor(path: string, key: string): string {
  return PROFILE_LABELS[path] ?? PROFILE_LABELS[key] ?? humanizeKey(key);
}
